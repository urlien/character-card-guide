#!/usr/bin/env node
// 无外部依赖，在系统临时目录验证导入校验及转换的保真行为。
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const scripts = dirname(fileURLToPath(import.meta.url));
const tmp = mkdtempSync(join(tmpdir(), 'mmd-skill-tests-'));
let count = 0;
function file(name, data) { const f = join(tmp, name); writeFileSync(f, typeof data === 'string' ? data : JSON.stringify(data)); return f; }
function run(script, args, expected = 0) {
  const result = spawnSync(process.execPath, [join(scripts, script), ...args], { encoding: 'utf8' });
  assert.equal(result.status, expected, `${script}: ${result.stdout}\n${result.stderr}`);
  count++;
  return result.stdout + result.stderr;
}
const persona = '<角色设定 名字：禾安>\n<关系>\n禾安是 {{user}} 的伙伴。\n</关系>\n</角色设定>';
const rule = { id: -1, scriptName: '按钮', findRegex: '{{intro}}', replaceString: '<button>问候</button>' };
const card = { chatVersion: 1, pageDepth: 2, beginning: '{{intro}}', statusbar: '', regex_scripts: [rule] };
const entry = { comment: '雨天', disable: false, constant: false, position: 4, role: 0, depth: 4, order: 12, probability: '50.00', key: '["雨"]', keysecondary: '["夜"]', content: '<雨天>\n仅在雨夜开启。\n</雨天>', uid: 7 };
const book = e => ({ entries: { 0: e } });
try {
  const personaPath = file('persona.txt', persona);
  run('validate.mjs', ['--persona', personaPath]);
  run('validate.mjs', ['--help']);
  run('validate.mjs', ['--unknown'], 1);
  run('validate.mjs', [file('card.json', card)]);
  run('validate.mjs', [file('beginning-only.json', { ...card, beginning: '禾安来了。', regex_scripts: [] })]);
  run('validate.mjs', [file('empty.json', { ...card, beginning: '', regex_scripts: [], personality: ' ' })], 1);
  run('validate.mjs', [file('4000.json', { ...card, beginning: '字'.repeat(4000) })]);
  run('validate.mjs', [file('4001.json', { ...card, beginning: '字'.repeat(4001) })], 1);
  run('validate.mjs', [file('mixed.json', { ...card, entries: {} })], 1);
  run('validate.mjs', [file('version-string.json', { ...card, chatVersion: '1' })], 1);
  run('validate.mjs', [file('fraction-id.json', { ...card, regex_scripts: [{ ...rule, id: -1.5 }] })], 1);
  run('validate.mjs', [file('repeat-id.json', { ...card, regex_scripts: [rule, { ...rule, findRegex: 'b' }] })], 1);
  run('validate.mjs', [file('bad-regex.json', { ...card, regex_scripts: [{ ...rule, findRegex: '/[/' }] })], 1);
  run('validate.mjs', [file('duplicate-literal.json', { ...card, regex_scripts: [rule, { ...rule, id: -2 }] })], 1);
  run('validate.mjs', [file('copy.json', { ...card, personality: persona }), '--persona', personaPath]);
  run('validate.mjs', [file('different-copy.json', { ...card, personality: persona.replace('伙伴', '邻居') }), '--persona', personaPath], 1);
  run('validate.mjs', ['--persona', file('broken-persona.txt', persona.replace('</关系>', '</姓名>'))], 1);
  const varsOutput = run('validate.mjs', [file('vars.json', { ...card, regex_scripts: [{ ...rule, replaceString: '<script>sdk.vars.get();</script>' }] })], 1);
  assert.match(varsOutput, /契约未补齐/);
  run('validate-worldbook.mjs', [file('book.json', book(entry))]);
  run('validate-worldbook.mjs', [file('plain.json', book({ ...entry, content: '原始纯文本' }))]);
  run('validate-worldbook.mjs', [file('3000.json', book({ ...entry, content: '字'.repeat(3000) }))]);
  run('validate-worldbook.mjs', [file('3001.json', book({ ...entry, content: '字'.repeat(3001) }))], 1);
  run('validate-worldbook.mjs', [file('keys-array.json', book({ ...entry, key: ['雨'] }))], 1);
  const extended = file('extended.json', book({ ...entry, variableCondition: { path: '阶段' } }));
  run('validate-worldbook.mjs', [extended], 1);
  const normalized = join(tmp, 'normalized.json');
  const original = { ...entry, constant: 'true', disable: 'true', content: '原始纯文本 {{user}}' };
  run('normalize-worldbook.mjs', ['--in', file('source.json', book(original)), '--out', normalized]);
  const normalizedData = JSON.parse(readFileSync(normalized));
  const normalizedEntry = normalizedData.entries[0];
  assert.deepEqual(normalizedEntry, { ...original, constant: true, disable: true });
  const normalizedAgain = join(tmp, 'normalized-again.json');
  run('normalize-worldbook.mjs', ['--in', normalized, '--out', normalizedAgain]);
  assert.equal(readFileSync(normalized, 'utf8'), readFileSync(normalizedAgain, 'utf8'));
  const refused = join(tmp, 'refused.json');
  run('normalize-worldbook.mjs', ['--in', extended, '--out', refused], 1);
  assert.equal(existsSync(refused), false);
  run('normalize-worldbook.mjs', ['--in', file('invalid-bool.json', book({ ...entry, disable: 'nope' })), '--out', refused], 1);
  run('normalize-worldbook.mjs', ['--in', file('invalid-prob.json', book({ ...entry, probability: 101 })), '--out', refused], 1);
  run('normalize-worldbook.mjs', ['--in', file('empty-entry.json', book({ ...entry, content: '' })), '--out', refused], 1);
  const uids = join(tmp, 'uids.json');
  const missingUid = { ...entry }; delete missingUid.uid;
  run('normalize-worldbook.mjs', ['--in', file('uid-source.json', { entries: [missingUid, { ...entry, uid: 0 }] }), '--out', uids]);
  const uidEntries = Object.values(JSON.parse(readFileSync(uids)).entries);
  assert.equal(uidEntries[1].uid, 0); assert.notEqual(uidEntries[0].uid, 0);
  const repair = join(tmp, 'repair.json');
  run('normalize-worldbook.mjs', ['--in', file('repair-source.json', book({ ...entry, content: '<雨天>\n下雨。' })), '--out', repair, '--repair-tags']);
  run('validate-worldbook.mjs', [repair]);
  const packed = join(tmp, 'packed.txt');
  const packArgs = ['--persona', personaPath, '--worldbook', file('pack-source.json', { entries: { 0: entry, 1: { ...entry, uid: 8, constant: true, probability: '25.00', content: '低概率常驻事件' }, 2: { ...entry, uid: 9, probability: '0.00', content: '零概率不进入' } } }), '--out', packed];
  run('pack-worldbook.mjs', packArgs);
  const packedText = readFileSync(packed, 'utf8');
  assert.match(packedText, /主要关键词任意一个（雨），并且同时满足次要关键词组（夜）/);
  assert.match(packedText, /25\.00%/); assert.doesNotMatch(packedText, /零概率不进入/);
  assert.equal(packedText.trim().endsWith('</补充世界设定>\n</角色设定>'), true);
  run('validate.mjs', ['--persona', packed]);
  run('pack-worldbook.mjs', ['--persona', personaPath, '--worldbook', extended, '--out', refused], 1);
  const tooLong = file('long-book.json', { entries: { 0: entry, 1: { ...entry, uid: 8, content: '不能随意截断的重要规则。'.repeat(100) } } });
  run('pack-worldbook.mjs', ['--persona', personaPath, '--worldbook', tooLong, '--out', refused, '--limit', '500'], 1);
  assert.equal(existsSync(refused), false);
  run('pack-worldbook.mjs', ['--persona', personaPath, '--worldbook', tooLong, '--out', packed, '--limit', '500', '--allow-partial']);
  assert.doesNotMatch(readFileSync(packed, 'utf8'), /不能随意截断/);
  const fixedPersona = '<角色设定 名字：禾安>\n<规则>\n{{user}}' + '字'.repeat(2100) + '\n</规则>\n</角色设定>';
  run('validate.mjs', [file('publish.json', { ...card, personality: fixedPersona, beginning: '字'.repeat(200) }), '--publish']);
  run('validate.mjs', [file('publish-short-first.json', { ...card, personality: fixedPersona, beginning: '字'.repeat(199) }), '--publish'], 1);
  const shortPersonaCard = file('publish-short-persona.json', { ...card, personality: persona, beginning: '字'.repeat(200) });
  const fixedBook = file('fixed-book.json', book({ ...entry, constant: true, probability: '100.00', content: '字'.repeat(2000) }));
  run('validate.mjs', [shortPersonaCard, '--publish', '--worldbook', fixedBook]);
  run('validate.mjs', [shortPersonaCard, '--publish', '--worldbook', file('disabled-book.json', book({ ...entry, disable: true, constant: true, probability: '100.00', content: '字'.repeat(2000) }))], 1);
  console.log(`PASS ${count} 次命令验证，保真、边界、错误及合并行为全部通过。`);
} finally { rmSync(tmp, { recursive: true, force: true }); }
